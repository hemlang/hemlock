#!/usr/bin/env python3
"""Generate tests/stdlib_gpu/test_codegen_diff_*.hml.

Differential test for gpu fn device code generation: every kernel runs both
under @stdlib/gpu_emu (Hemlock semantics, the reference) and compiled to
OpenCL C on a real device, over edge-value inputs. Results must match
exactly (transcendental math within a tolerance), and errors must name the
same work-item with the same message.

Regenerate after changing the operator or type coverage:
    python3 tests/stdlib_gpu/gen_codegen_diff.py
"""

import os

TYPES = ["i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "f32", "f64"]
INTS = TYPES[:8]
FLOATS = ["f32", "f64"]

# Hemlock's promotion table (src/shared/type_promotion.c)
PRIORITY = {"i8": 0, "u8": 1, "i16": 2, "u16": 3, "i32": 4, "u32": 5,
            "i64": 6, "u64": 7, "f32": 8, "f64": 9}


def promote(a, b):
    if a == b:
        return a
    if "f64" in (a, b):
        return "f64"
    if "f32" in (a, b):
        other = b if a == "f32" else a
        return "f64" if other in ("i64", "u64") else "f32"
    return a if PRIORITY[a] >= PRIORITY[b] else b


def neg_type(t):
    return {"u8": "i16", "u16": "i32", "u32": "i64", "u64": "i64"}.get(t, t)


BOUNDS = {
    "i8": (-128, 127), "i16": (-32768, 32767),
    "i32": (-2147483648, 2147483647),
    "i64": (-9223372036854775808, 9223372036854775807),
    "u8": (0, 255), "u16": (0, 65535), "u32": (0, 4294967295),
    "u64": (0, 18446744073709551615),
}


def int_lit(t, v):
    if t == "i64" and v == -9223372036854775808:
        return "(-9223372036854775807 - 1)"
    if t == "i32":
        return str(v) if v != -2147483648 else "(-2147483647 - 1)"
    return "%s(%d)" % (t, v)


def float_lit(t, text):
    special = {"nan": "(0.0 / 0.0)", "inf": "(1.0 / 0.0)", "-inf": "(-1.0 / 0.0)"}
    v = special.get(text, text)
    return v if t == "f64" else "f32(%s)" % v


def values(t):
    """Edge-heavy inputs for type t, as Hemlock expressions of exactly type t."""
    if t in INTS:
        lo, hi = BOUNDS[t]
        cands = [lo, lo + 1, -100, -7, -1, 0, 1, 2, 3, 7, 8, 15, 16, 31, 32, 33,
                 63, 64, 100, 200, 300, 70000, hi // 2, hi - 1, hi]
        out = []
        for v in cands:
            if lo <= v <= hi and v not in out:
                out.append(v)
        return [int_lit(t, v) for v in out]
    texts = ["0.0", "-0.0", "0.5", "-1.5", "1.0", "2.0", "3.0", "7.25", "-7.25",
             "100.0", "255.5", "-129.0", "65535.0", "4294967296.0", "1e10", "-1e10",
             "9.3e18", "-9.3e18", "3.0e38", "1e-30", "nan", "inf", "-inf"]
    if t == "f64":
        texts += ["1e300", "-1e300", "1e-310", "9223372036854775807.0", "-9223372036854775808.0"]
    return [float_lit(t, x) for x in texts]


def pair_inputs(ta, tb):
    """Zip two value lists into pairs, cycling the shorter one twice (offset)
    so each a-value meets several b-values."""
    va, vb = values(ta), values(tb)
    n = max(len(va), len(vb))
    a, b = [], []
    for i in range(2 * n):
        a.append(va[i % len(va)])
        b.append(vb[(i * 7 + i // len(vb)) % len(vb)])
    return a, b


PAIRS = [(t, t) for t in TYPES] + [
    ("i32", "u32"), ("i8", "u8"), ("u8", "i32"), ("i16", "u16"), ("i64", "u64"),
    ("i32", "i64"), ("u32", "i64"), ("u8", "f32"), ("f32", "f64"), ("i64", "f32"),
    ("u64", "f32"), ("i16", "i32"), ("u16", "i8"), ("i32", "f64"),
]
# Not covered: i32/u32 with f32. hemlockc computes those in f64 and rounds
# once, unlike the interpreter (a known pre-existing parity bug), so the
# emulator itself disagrees across backends there.

ARITH = [("add", "+"), ("sub", "-"), ("mul", "*"), ("mod", "%")]
CMP = [("lt", "<"), ("le", "<="), ("gt", ">"), ("ge", ">="), ("eq", "=="), ("ne", "!=")]
BITS = [("and", "&"), ("or", "|"), ("xor", "^"), ("shl", "<<"), ("shr", ">>")]

MATH1 = ["sqrt", "floor", "ceil", "exp", "log", "sin", "cos"]
INEXACT = {"exp", "log", "sin", "cos", "pow"}


def hml_array(items):
    return "[" + ", ".join(items) + "]"


class Out:
    """One generated test file (kept small: each runs in a few seconds)."""

    def __init__(self, name, what):
        self.name = name
        self.lines = [
            "// GENERATED by tests/stdlib_gpu/gen_codegen_diff.py: do not edit by hand.",
            "// Differential test (%s): gpu fn kernels compiled for the device must" % what,
            "// match @stdlib/gpu_emu (Hemlock semantics) exactly, errors included.",
            'import { gpu_context, DEVICE_ALL } from "@stdlib/gpu";',
            'import { run_case, report } from "./diff_harness.hml";',
            "",
            "let ctx = gpu_context({ device_type: DEVICE_ALL });",
            "",
        ]

    def write(self):
        self.lines += ["ctx.release();", "report();"]
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)), self.name)
        with open(path, "w") as f:
            f.write("\n".join(self.lines) + "\n")
        print("wrote", path)


def main():
    files = [
        Out("test_codegen_diff_binary_same.hml", "binary operators, same types"),
        Out("test_codegen_diff_binary_mixed.hml", "binary operators, mixed types"),
        Out("test_codegen_diff_unary.hml", "unary operators and conversions, integers"),
        Out("test_codegen_diff_unary_float.hml", "unary operators and conversions, floats"),
        Out("test_codegen_diff_math.hml", "math intrinsics"),
    ]
    w = files[0].lines.append

    # ---- binary operators, one kernel per type pair ----
    for ta, tb in PAIRS:
        w = files[0 if ta == tb else 1].lines.append
        r = promote(ta, tb)
        d = "f64" if (ta in INTS and tb in INTS) else r
        ints = ta in INTS and tb in INTS
        kname = "bin_%s_%s" % (ta, tb)
        w("gpu fn %s(op: i32, a: gpu_buffer<%s>, b: gpu_buffer<%s>, r: gpu_buffer<%s>, d: gpu_buffer<%s>, c: gpu_buffer<i32>) {"
          % (kname, ta, tb, r, d))
        w("    let i: u32 = global_id(0);")
        w("    switch (op) {")
        k = 0
        ops = []
        for name, sym in ARITH:
            w("        case %d: r[i] = a[i] %s b[i]; break;" % (k, sym)); ops.append((k, name, "r")); k += 1
        w("        case %d: d[i] = a[i] / b[i]; break;" % k); ops.append((k, "div", "d")); k += 1
        for name, sym in CMP:
            w("        case %d: c[i] = i32(a[i] %s b[i]); break;" % (k, sym)); ops.append((k, name, "c")); k += 1
        w("        case %d: c[i] = i32(a[i] && b[i]); break;" % k); ops.append((k, "land", "c")); k += 1
        if ints:
            for name, sym in BITS:
                w("        case %d: r[i] = a[i] %s b[i]; break;" % (k, sym)); ops.append((k, name, "r")); k += 1
        w("    }")
        w("}")
        a, b = pair_inputs(ta, tb)
        for op, name, _ in ops:
            w('run_case(ctx, %s, "%s %s", %d, [%s, %s], ["%s", "%s"], ["%s", "%s", "i32"], 0.0);'
              % (kname, kname, name, op, hml_array(a), hml_array(b), ta, tb, r, d))
        w("")

    # ---- unary operators and every conversion, one kernel per type ----
    for t in TYPES:
        w = files[3 if t in FLOATS else 2].lines.append
        kname = "un_%s" % t
        n = neg_type(t)
        params = ["op: i32", "a: gpu_buffer<%s>" % t, "ng: gpu_buffer<%s>" % n, "nt: gpu_buffer<i32>"]
        if t in INTS:
            params.append("bn: gpu_buffer<%s>" % t)
        params += ["o_%s: gpu_buffer<%s>" % (u, u) for u in TYPES]
        w("gpu fn %s(%s) {" % (kname, ", ".join(params)))
        w("    let i: u32 = global_id(0);")
        w("    switch (op) {")
        ops = [(0, "neg"), (1, "not")]
        w("        case 0: ng[i] = -a[i]; break;")
        w("        case 1: nt[i] = i32(!a[i]); break;")
        k = 2
        if t in INTS:
            w("        case 2: bn[i] = ~a[i]; break;")
            ops.append((2, "bitnot"))
            k = 3
        for u in TYPES:
            w("        case %d: o_%s[i] = %s(a[i]); break;" % (k, u, u)); ops.append((k, "to_" + u)); k += 1
        # implicit conversions: typed local and buffer store
        w("        case %d: let v: u8 = a[i]; o_u8[i] = v; break;" % k); ops.append((k, "let_u8")); k += 1
        w("        case %d: o_i32[i] = a[i]; break;" % k); ops.append((k, "store_i32")); k += 1
        w("    }")
        w("}")
        outs = [n, "i32"] + ([t] if t in INTS else []) + TYPES
        vals = values(t) * 2
        for op, name in ops:
            w('run_case(ctx, %s, "%s %s", %d, [%s], ["%s"], [%s], 0.0);'
              % (kname, kname, name, op, hml_array(vals), t, ", ".join('"%s"' % o for o in outs)))
        w("")

    # ---- math intrinsics on floats ----
    w = files[4].lines.append
    for t in FLOATS:
        kname = "math_%s" % t
        w("gpu fn %s(op: i32, a: gpu_buffer<%s>, b: gpu_buffer<%s>, r: gpu_buffer<%s>) {" % (kname, t, t, t))
        w("    let i: u32 = global_id(0);")
        w("    switch (op) {")
        names = MATH1 + ["pow", "abs", "min", "max"]
        for k, name in enumerate(names):
            if name in ("pow", "min", "max"):
                w("        case %d: r[i] = %s(a[i], b[i]); break;" % (k, name))
            else:
                w("        case %d: r[i] = %s(a[i]); break;" % (k, name))
        w("    }")
        w("}")
        a, b = pair_inputs(t, t)
        for k, name in enumerate(names):
            tol = "1e-6" if (name in INEXACT and t == "f32") else ("1e-13" if name in INEXACT else "0.0")
            w('run_case(ctx, %s, "%s %s", %d, [%s, %s], ["%s", "%s"], ["%s"], %s);'
              % (kname, kname, name, k, hml_array(a), hml_array(b), t, t, t, tol))
        w("")

    # ---- integer abs/min/max and math on integers (f64 results) ----
    for t in ["i8", "i32", "i64", "u8", "u32"]:
        kname = "imath_%s" % t
        w("gpu fn %s(op: i32, a: gpu_buffer<%s>, b: gpu_buffer<%s>, r: gpu_buffer<%s>, f: gpu_buffer<f64>) {" % (kname, t, t, t))
        w("    let i: u32 = global_id(0);")
        w("    switch (op) {")
        w("        case 0: r[i] = abs(a[i]); break;")
        w("        case 1: r[i] = min(a[i], b[i]); break;")
        w("        case 2: r[i] = max(a[i], b[i]); break;")
        w("        case 3: f[i] = sqrt(a[i]); break;")
        w("        case 4: f[i] = floor(a[i]); break;")
        w("    }")
        w("}")
        a, b = pair_inputs(t, t)
        for k, name in enumerate(["abs", "min", "max", "sqrt", "floor"]):
            w('run_case(ctx, %s, "%s %s", %d, [%s, %s], ["%s", "%s"], ["%s", "f64"], 0.0);'
              % (kname, kname, name, k, hml_array(a), hml_array(b), t, t, t))
        w("")

    for f in files:
        f.write()


if __name__ == "__main__":
    main()
